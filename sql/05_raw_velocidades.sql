-- Archivo diario de velocidades DTPM (hoja "velocidad"), sólo filas de la U16; una fila por expedición.
CREATE TABLE IF NOT EXISTS raw_velocidades (
  id                   BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  carga_id             BIGINT UNSIGNED NOT NULL,
  numero_fila          INT UNSIGNED NOT NULL,
  un                   VARCHAR(20)  NULL,
  operador             VARCHAR(80)  NULL,
  servicio             VARCHAR(20)  NULL,
  patente              VARCHAR(12)  NULL,
  sentido              VARCHAR(20)  NULL,
  inicio               TIME         NULL,
  intervalo_salida     TIME         NULL,
  control              TIME         NULL,
  fin                  TIME         NULL,
  distancia_m          DECIMAL(14,3) NULL,
  tiempo               TIME         NULL,
  velocidad_km_hr      DECIMAL(12,6) NULL,
  capacidad            INT          NULL,
  estado               VARCHAR(10)  NULL,
  fecha                DATE         NOT NULL,
  dia                  TINYINT      NULL,
  tipo_dia             VARCHAR(20)  NULL,
  periodo              VARCHAR(60)  NULL,
  cada_5_minutos       TIME         NULL,
  cada_media_hora      TIME         NULL,
  PRIMARY KEY (id),
  KEY ix_raw_velocidades_carga (carga_id),
  KEY ix_raw_velocidades_fecha (fecha, servicio, sentido),
  CONSTRAINT fk_raw_velocidades_carga FOREIGN KEY (carga_id) REFERENCES control_carga (carga_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
